/**
 * 键位提示行拼装单源（07 篇 §4.4 用户面话术律·律三——2026-09-30 话术批落码）。
 *
 * 律三定形：键位提示行**全局统一形**——
 * - 串接符恒「 · 」（前后各一空格的全角间隔号），模板族 `esc 返回 · enter 选定 · q 退出`；
 * - **载体间零漂移**：panels/ 全部副屏 + 向导/引导面板 + 主屏面板的底行键位
 *   提示一律经本件拼装——修前各面板各写各的字符串退役，串接格式自此单源。
 *
 * 键名事实（esc / enter / q / ctrl+p 等实际键名）不归本件管——本件只统一
 * 拼装与格式；键名来源两律：
 * - **键位册在册动作**的键名显示经 keys/registry.ts 的 keyText(actionId)
 *   单源取（用户覆盖 keybindings 后文案随动——transcript 思考标签等消费位
 *   既有律，面板提示若引用在册动作同律走 keyText，不自写键名）；
 * - **面板本地键面**（↑↓ / u / r / space 等选择器自持键）按各面板键面事实
 *   直书——键位事实是红线（实际键名不改饰）。
 *
 * 空段容忍：入参中的空串段直接跳过——调用侧按态拼段时守卫省写
 * （例：空表面板只留「q/esc 返回」一段时，其余段传空串即无痕落位）。
 */

/**
 * 拼装键位提示行：各段以「 · 」串接，空串段跳过。
 *
 * @param segments 提示段（每段 = 键名 + 空格 + 动作词〔如 `enter 选定`〕，
 *   或纯说明段〔如 `打字过滤`〕）
 * @returns 拼装后的提示行（全部为空段时为空串——调用侧按需省行）
 */
export function hintLine(...segments: string[]): string {
  return segments.filter((segment) => segment !== '').join(' · ');
}
